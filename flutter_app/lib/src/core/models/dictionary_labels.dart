/// Case-insensitive index of [kTagArabicLabels] — Supabase stores tags
/// lowercased, while the map above is keyed in Title Case for readability.
final Map<String, String> _kTagArabicLabelsLower = {
  for (final entry in kTagArabicLabels.entries)
    entry.key.toLowerCase(): entry.value,
};

/// Arabic label for [tag], falling back to the raw English value if it has
/// no translation yet. Matches case-insensitively since the dataset stores
/// tags lowercased.
String tagArabicLabel(String tag) =>
    _kTagArabicLabelsLower[tag.trim().toLowerCase()] ?? tag;
