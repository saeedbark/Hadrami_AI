/// Arabic display labels for dictionary entry metadata whose raw values are
/// stored in English in the dataset/Supabase (part of speech, region, tags).
///
/// The API/data layer keeps using the raw English strings for filtering and
/// querying — only the label shown to the user is translated here. Unknown
/// values fall back to the raw English text instead of throwing, so a new
/// tag added to the dataset never breaks rendering; it just needs an entry
/// added to [kTagArabicLabels] to show translated.
library;

enum PartOfSpeech {
  noun('Noun', 'اسم'),
  verb('Verb', 'فعل'),
  adjective('Adjective', 'صفة'),
  adverb('Adverb', 'ظرف'),
  preposition('Preposition', 'حرف جر'),
  particle('Particle', 'أداة'),
  expression('Expression', 'تعبير'),
  verbPhrase('Verb Phrase', 'عبارة فعلية');

  const PartOfSpeech(this.apiValue, this.arabicLabel);

  final String apiValue;
  final String arabicLabel;

  /// Translates a raw POS string from the API (e.g. `'Noun'`, or a compound
  /// like `'Noun / Verb'` / `'Noun/Adjective'`) into Arabic, translating each
  /// part of a compound and re-joining with the same separator. Falls back
  /// to [raw] untouched for anything unrecognized.
  static String arabicLabelFor(String raw) {
    if (raw.trim().isEmpty) return raw;
    final separator =
        raw.contains(' / ') ? ' / ' : (raw.contains('/') ? '/' : null);
    if (separator == null) {
      return _lookup(raw) ?? raw;
    }
    return raw
        .split(separator)
        .map((part) => _lookup(part.trim()) ?? part.trim())
        .join(' / ');
  }

  static String? _lookup(String raw) {
    for (final pos in PartOfSpeech.values) {
      if (pos.apiValue.toLowerCase() == raw.toLowerCase()) {
        return pos.arabicLabel;
      }
    }
    return null;
  }
}

enum WordRegion {
  general('General', 'عام'),
  rural('Rural', 'ريفي'),
  coast('Coast', 'ساحل'),
  coastal('Coastal', 'ساحلي'),
  wadi('Wadi', 'وادي'),
  valleys('Valleys', 'أودية'),
  interior('Interior', 'داخلي'),
  nature('Nature', 'طبيعة'),
  agriculture('Agriculture', 'زراعي'),
  bedouin('Bedouin', 'بدوي'),
  desert('Desert', 'صحراء'),
  badia('Badia', 'بادية'),
  badiyah('Badiyah', 'البادية'),
  ghaylBaWazir('Ghayl Ba Wazir', 'غيل باوزير');

  const WordRegion(this.apiValue, this.arabicLabel);

  final String apiValue;
  final String arabicLabel;

  /// Same compound-aware translation as [PartOfSpeech.arabicLabelFor], for
  /// region values like `'Coast / Wadi'` or `'General / Rural'`.
  static String arabicLabelFor(String raw) {
    if (raw.trim().isEmpty) return raw;
    final separator =
        raw.contains(' / ') ? ' / ' : (raw.contains('/') ? '/' : null);
    if (separator == null) {
      return _lookup(raw) ?? raw;
    }
    return raw
        .split(separator)
        .map((part) => _lookup(part.trim()) ?? part.trim())
        .join(' / ');
  }

  static String? _lookup(String raw) {
    for (final region in WordRegion.values) {
      if (region.apiValue.toLowerCase() == raw.toLowerCase()) {
        return region.arabicLabel;
      }
    }
    return null;
  }
}

